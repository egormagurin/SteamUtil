// Steam Utilities — Release Calendar
// Renders a competition heatmap of upcoming Steam releases so you can spot
// low-traffic, low-wishlist release days.
//
// Two runtime modes, auto-detected:
//   • Backend mode (local `npm start`): talks to the Express API at api/*,
//     can trigger live refreshes with a progress bar.
//   • Static mode (GitHub Pages): no backend, so it loads a pre-built
//     data/upcoming.json that GitHub Actions refreshes every 3 hours.

const POP_WEIGHT = 4; // how much heavier a high-wishlist game counts vs. a small one
const MONTH_NAMES = ['January','February','March','April','May','June','July','August','September','October','November','December'];
const WEEKDAYS = ['Sun','Mon','Tue','Wed','Thu','Fri','Sat'];

const state = {
  games: [],
  fetchedAt: null,
  totalAvailable: null,
  partial: false,
  staticMode: false,
  threshold: 300,
  windowMonths: 6,
  multiplier: 10,
  selectedDate: null,
  // Tag Explorer
  tagNames: {},
  selectedTag: null,
  tagWindowMonths: 12,
  tagThreshold: 300,
};

const $ = (sel) => document.querySelector(sel);

// ---- Data loading ----------------------------------------------------------

function applyDataset(data) {
  state.games = data.games || [];
  state.fetchedAt = data.fetchedAt;
  state.totalAvailable = data.totalAvailable;
  state.partial = !!data.partial;
  state.tagNames = data.tagNames || {};
  renderActiveView();
}

async function loadData() {
  const res = await fetch('api/data');
  if (res.status === 404) return false;
  applyDataset(await res.json());
  return true;
}

// Static (GitHub Pages) mode: load the pre-built data file directly.
async function loadStaticData() {
  const label = $('#progress-label');
  $('#progress').classList.remove('hidden');
  try {
    const res = await fetch('data/upcoming.json', { cache: 'no-cache' });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    applyDataset(await res.json());
    $('#progress').classList.add('hidden');
  } catch (e) {
    label.textContent = `Could not load data/upcoming.json (${e.message}). ` +
      `It is generated by the GitHub Actions deploy — check that the workflow has run.`;
  }
}

// Hide the live-only controls when there's no backend to talk to.
function enterStaticMode() {
  state.staticMode = true;
  const refresh = $('#refresh');
  refresh.disabled = true;
  refresh.textContent = '↻ Auto-updated every 3h';
  refresh.title = 'Static GitHub Pages build — data is refreshed every 3 hours by GitHub Actions.';
  const depth = $('#depth');
  depth.disabled = true;
  depth.title = 'Fetch depth is fixed in the static build.';
}

async function pollStatusUntilDone() {
  const progress = $('#progress');
  const fill = $('#progress-fill');
  const label = $('#progress-label');
  progress.classList.remove('hidden');

  while (true) {
    const st = await (await fetch('api/status')).json();
    if (st.error) {
      label.textContent = `Error: ${st.error}`;
      break;
    }
    if (st.running) {
      const pct = st.total ? Math.round((st.loaded / st.total) * 100) : 0;
      fill.style.width = `${pct}%`;
      const counts = `${st.loaded.toLocaleString()} / ${st.total.toLocaleString()}`;
      label.textContent = st.notice
        ? `⏳ ${st.notice} (${counts})`
        : st.phase === 'followers'
          ? `Fetching follower counts (wishlist proxy)… ${counts}`
          : `Fetching upcoming games from Steam… ${counts}`;
    } else if (st.hasData) {
      fill.style.width = '100%';
      progress.classList.add('hidden');
      await loadData();
      break;
    } else {
      label.textContent = 'Waiting for data…';
    }
    await new Promise((r) => setTimeout(r, 800));
  }
}

async function init() {
  // Probe for a live backend. On GitHub Pages api/status is a 404 (HTML), so
  // either the request is not ok or JSON parsing throws — both mean static mode.
  let st = null;
  try {
    const res = await fetch('api/status');
    if (res.ok) st = await res.json();
  } catch { /* no backend reachable */ }

  if (!st) {
    enterStaticMode();
    await loadStaticData();
    return;
  }

  if (st.hasData) {
    await loadData();
    if (st.running) pollStatusUntilDone(); // a refresh is mid-flight; update when done
  } else {
    pollStatusUntilDone();
  }
}

async function refresh() {
  const depth = $('#depth').value;
  await fetch(`api/refresh?depth=${depth}`, { method: 'POST' });
  pollStatusUntilDone();
}

// ---- Date helpers -----------------------------------------------------------

function todayParts() {
  const d = new Date();
  return { y: d.getFullYear(), m: d.getMonth(), day: d.getDate() };
}

function isoToParts(iso) {
  const [y, m, d] = iso.split('-').map(Number);
  return { y, m: m - 1, d };
}

function fmtPrice(cents) {
  // Upcoming games with no announced price come through as null or 0; show
  // both neutrally rather than claiming "Free".
  if (cents == null || cents === 0) return '—';
  return '$' + (cents / 100).toFixed(2);
}

// Compact number: 54554 -> "54.5k", 1005575 -> "1M".
function fmtCount(n) {
  if (n == null) return '—';
  if (n >= 1e6) return (n / 1e6).toFixed(n >= 1e7 ? 0 : 1) + 'M';
  if (n >= 1e3) return (n / 1e3).toFixed(n >= 1e4 ? 0 : 1) + 'k';
  return String(n);
}

// Short release label honoring precision: "Aug 7", "Aug 2026", "Q3 2026", "2026".
function fmtReleaseShort(g) {
  if (!g.releaseDate) return 'TBA';
  const { y, m, d } = isoToParts(g.releaseDate);
  if (g.datePrecision === 'day') return `${MONTH_NAMES[m].slice(0, 3)} ${d}`;
  if (g.datePrecision === 'month') return `${MONTH_NAMES[m].slice(0, 3)} ${y}`;
  if (g.datePrecision === 'quarter') return `Q${Math.floor(m / 3) + 1} ${y}`;
  return `${y}`;
}

// Window bounds shared by best-days, competitors, and the tag explorer.
function windowBounds(months = state.windowMonths) {
  const t = todayParts();
  const pad = (n) => String(n).padStart(2, '0');
  const todayIso = `${t.y}-${pad(t.m + 1)}-${pad(t.day)}`;
  const monthStartIso = `${t.y}-${pad(t.m + 1)}-01`;
  const endY = t.y + Math.floor((t.m + months) / 12);
  const endM = (t.m + months) % 12;
  const endIso = `${endY}-${pad(endM + 1)}-01`;
  return { todayIso, monthStartIso, endIso };
}

// ---- Aggregation ------------------------------------------------------------

// Build a map of ISO date -> { total, popular, games[] } for day-precise games.
function aggregateByDay() {
  const byDay = new Map();
  for (const g of state.games) {
    if (g.datePrecision !== 'day' || !g.releaseDate) continue;
    let entry = byDay.get(g.releaseDate);
    if (!entry) {
      entry = { total: 0, popular: 0, games: [] };
      byDay.set(g.releaseDate, entry);
    }
    entry.total += 1;
    if (g.rank <= state.threshold) entry.popular += 1;
    entry.games.push(g);
  }
  for (const entry of byDay.values()) {
    entry.index = entry.total + entry.popular * POP_WEIGHT;
    entry.games.sort((a, b) => a.rank - b.rank);
  }
  return byDay;
}

function heatLevel(index) {
  if (index <= 0) return 0;
  if (index <= 3) return 1;
  if (index <= 8) return 2;
  if (index <= 16) return 3;
  return 4;
}

// Coarse buckets (month/quarter/year precision) -> count per "YYYY period".
function aggregateCoarse() {
  const buckets = new Map();
  for (const g of state.games) {
    if (g.datePrecision === 'day' || !g.releaseDate) continue;
    const { y, m } = isoToParts(g.releaseDate);
    let key, label, sort;
    if (g.datePrecision === 'month') {
      key = `${y}-${m}`; label = `${MONTH_NAMES[m].slice(0,3)} ${y}`; sort = y * 100 + m;
    } else if (g.datePrecision === 'quarter') {
      const q = Math.floor(m / 3) + 1; key = `${y}-Q${q}`; label = `Q${q} ${y}`; sort = y * 100 + m;
    } else {
      key = `${y}`; label = `${y}`; sort = y * 100 + 11;
    }
    let b = buckets.get(key);
    if (!b) { b = { label, sort, count: 0 }; buckets.set(key, b); }
    b.count += 1;
  }
  return [...buckets.values()].sort((a, b) => a.sort - b.sort);
}

// ---- Rendering --------------------------------------------------------------

function render() {
  state.threshold = +$('#threshold').value;
  state.windowMonths = +$('#window').value;
  state.multiplier = +$('#multiplier').value;

  const byDay = aggregateByDay();
  renderBanner();
  renderCalendar(byDay);
  renderBestDays(byDay);
  renderCompetitors();
  renderDayDetail(byDay);
  renderCoarse();
  renderStats(byDay);
  renderFreshness();
}

function renderBanner() {
  const b = $('#updated-banner');
  if (!state.fetchedAt) { b.classList.add('hidden'); return; }
  const d = new Date(state.fetchedAt);
  const abs = d.toLocaleString(undefined, {
    year: 'numeric', month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit',
  });
  const mins = Math.round((Date.now() - d.getTime()) / 60000);
  const rel = mins < 1 ? 'just now'
    : mins < 60 ? `${mins} min ago`
    : mins < 1440 ? `${Math.round(mins / 60)} h ago`
    : `${Math.round(mins / 1440)} d ago`;
  const tail = state.staticMode ? ' · auto-updates every 3h via GitHub Actions' : '';
  b.classList.remove('hidden');
  b.innerHTML = `<span class="ub-dot">●</span> <span>Data last updated <strong>${abs}</strong></span>` +
    `<span class="ub-rel">(${rel})${tail}</span>`;
}

// Most-followed upcoming games that land within the selected window.
function renderCompetitors() {
  const card = $('#competitors-card');
  const ol = $('#competitors');
  const { monthStartIso, endIso } = windowBounds();
  const list = state.games
    .filter((g) => g.followers != null && g.releaseDate &&
      g.releaseDate >= monthStartIso && g.releaseDate < endIso)
    .sort((a, b) => b.followers - a.followers)
    .slice(0, 12);

  if (list.length === 0) {
    card.classList.add('hidden');
    return;
  }
  card.classList.remove('hidden');
  ol.innerHTML = list.map((g) => {
    const wl = fmtCount(Math.round(g.followers * state.multiplier));
    return `<li data-appid="${g.appid}" title="≈ ${wl} est. wishlists (followers × ${state.multiplier})">
      <span class="co-name">${escapeHtml(g.name)}</span>
      <span class="co-foll">★ ${fmtCount(g.followers)}</span>
      <span class="co-date">${fmtReleaseShort(g)}</span>
    </li>`;
  }).join('');
  ol.querySelectorAll('li[data-appid]').forEach((li) => {
    li.addEventListener('click', () =>
      window.open(`https://store.steampowered.com/app/${li.dataset.appid}`, '_blank', 'noopener'));
  });
}

function renderCalendar(byDay) {
  const cal = $('#calendar');
  cal.innerHTML = '';
  const t = todayParts();
  const todayIso = `${t.y}-${String(t.m + 1).padStart(2, '0')}-${String(t.day).padStart(2, '0')}`;

  for (let offset = 0; offset < state.windowMonths; offset++) {
    const y = t.y + Math.floor((t.m + offset) / 12);
    const m = (t.m + offset) % 12;
    cal.appendChild(renderMonth(y, m, byDay, todayIso));
  }
}

function renderMonth(year, month, byDay, todayIso) {
  const wrap = document.createElement('div');
  wrap.className = 'month';

  // Month-level totals
  let mTotal = 0, mPopular = 0;
  for (const [iso, e] of byDay) {
    const p = isoToParts(iso);
    if (p.y === year && p.m === month) { mTotal += e.total; mPopular += e.popular; }
  }

  const title = document.createElement('div');
  title.className = 'month-title';
  title.innerHTML = `<span>${MONTH_NAMES[month]} ${year}</span>
    <span class="month-meta">${mTotal} games · ${mPopular} high-wishlist</span>`;
  wrap.appendChild(title);

  const wd = document.createElement('div');
  wd.className = 'weekdays';
  wd.innerHTML = WEEKDAYS.map((d) => `<div class="weekday">${d}</div>`).join('');
  wrap.appendChild(wd);

  const days = document.createElement('div');
  days.className = 'days';

  const firstDow = new Date(Date.UTC(year, month, 1)).getUTCDay();
  const daysInMonth = new Date(Date.UTC(year, month + 1, 0)).getUTCDate();

  for (let i = 0; i < firstDow; i++) {
    const empty = document.createElement('div');
    empty.className = 'day empty';
    days.appendChild(empty);
  }

  for (let d = 1; d <= daysInMonth; d++) {
    const iso = `${year}-${String(month + 1).padStart(2, '0')}-${String(d).padStart(2, '0')}`;
    const entry = byDay.get(iso);
    const cell = document.createElement('div');
    const level = entry ? heatLevel(entry.index) : 0;
    cell.className = `day heat-${level}`;
    if (iso < todayIso) cell.classList.add('past');
    if (state.selectedDate === iso) cell.classList.add('selected');

    let inner = `<div class="day-num">${d}</div>`;
    if (entry) {
      cell.classList.add('has-games');
      inner += `<div class="day-count">${entry.total}</div>`;
      inner += `<div class="day-label">game${entry.total === 1 ? '' : 's'}</div>`;
      if (entry.popular > 0) inner += `<div class="day-pop">${entry.popular}</div>`;
      cell.addEventListener('click', () => selectDay(iso));
    }
    cell.innerHTML = inner;
    days.appendChild(cell);
  }

  wrap.appendChild(days);
  return wrap;
}

function selectDay(iso) {
  state.selectedDate = iso;
  render(); // render() draws the detail panel for the selected day
}

// Draw the day-detail panel for state.selectedDate (no-op if none / not in view).
function renderDayDetail(byDay) {
  const iso = state.selectedDate;
  const detail = $('#day-detail');
  if (!iso || !byDay.has(iso)) { detail.classList.add('hidden'); return; }
  const entry = byDay.get(iso);
  const { y, m, d } = isoToParts(iso);
  detail.classList.remove('hidden');
  $('#day-detail-title').textContent =
    `${MONTH_NAMES[m]} ${d}, ${y} — ${entry.total} game${entry.total === 1 ? '' : 's'}`;

  // Day-level wishlist estimate from games we have follower data for.
  const withFoll = entry.games.filter((g) => g.followers != null);
  const dayFollowers = withFoll.reduce((s, g) => s + g.followers, 0);
  const summary = $('#day-detail-summary');
  if (withFoll.length > 0) {
    summary.classList.remove('hidden');
    summary.innerHTML = `Top-game followers this day: <b>${fmtCount(dayFollowers)}</b> ` +
      `→ ≈ <b>${fmtCount(Math.round(dayFollowers * state.multiplier))}</b> est. wishlists ` +
      `(${withFoll.length}/${entry.total} games measured).`;
  } else {
    summary.classList.add('hidden');
  }

  $('#day-detail-list').innerHTML = entry.games.map((g) => {
    const hot = g.rank <= state.threshold ? ' hot' : '';
    const foll = g.followers != null
      ? `<span class="game-foll" title="Community followers — a public wishlist proxy">★ ${fmtCount(g.followers)} <span class="gf-wish">≈${fmtCount(Math.round(g.followers * state.multiplier))} wl</span></span>`
      : '';
    return `<li>
      <span class="game-main">
        <a href="https://store.steampowered.com/app/${g.appid}" target="_blank" rel="noopener">${escapeHtml(g.name)}</a>
        <span class="game-sub"><span class="game-rank${hot}" title="Popularity rank (lower = more wishlisted)">#${g.rank.toLocaleString()}</span> · ${fmtPrice(g.priceCents)}</span>
      </span>
      ${foll}
    </li>`;
  }).join('');
}

function renderBestDays(byDay) {
  const { todayIso, endIso } = windowBounds();

  const candidates = [...byDay.entries()]
    .filter(([iso]) => iso >= todayIso && iso < endIso)
    .map(([iso, e]) => ({ iso, ...e }))
    .sort((a, b) => a.index - b.index || a.iso.localeCompare(b.iso))
    .slice(0, 12);

  const ol = $('#best-days');
  if (candidates.length === 0) {
    ol.innerHTML = '<li class="bd-meta">No dated games in this window yet.</li>';
    return;
  }
  ol.innerHTML = candidates.map((c) => {
    const { y, m, d } = isoToParts(c.iso);
    return `<li data-iso="${c.iso}">
      <span class="bd-date">${WEEKDAYS[new Date(Date.UTC(y, m, d)).getUTCDay()]} ${MONTH_NAMES[m].slice(0,3)} ${d}</span>
      <span class="bd-meta"> — ${c.total} game${c.total===1?'':'s'}, ${c.popular} high-wishlist</span>
    </li>`;
  }).join('');
  ol.querySelectorAll('li[data-iso]').forEach((li) => {
    li.addEventListener('click', () => {
      if (byDay.has(li.dataset.iso)) selectDay(li.dataset.iso);
    });
  });
}

function renderCoarse() {
  const list = $('#coarse-list');
  const buckets = aggregateCoarse().slice(0, 12);
  if (buckets.length === 0) { list.innerHTML = '<li class="ct-count">none</li>'; return; }
  list.innerHTML = buckets.map((b) =>
    `<li><span>${b.label}</span><span class="ct-count">${b.count}</span></li>`).join('');
}

function renderStats(byDay) {
  let dated = 0;
  for (const e of byDay.values()) dated += e.total;
  const coarse = state.games.filter((g) => g.releaseDate && g.datePrecision !== 'day').length;
  const undated = state.games.filter((g) => !g.releaseDate).length;
  $('#stats').textContent =
    `${state.games.length.toLocaleString()} games loaded · ${dated.toLocaleString()} with exact dates · ${coarse.toLocaleString()} coarse · ${undated.toLocaleString()} undated` +
    (state.totalAvailable ? ` · ${state.totalAvailable.toLocaleString()} total upcoming on Steam` : '');
}

function renderFreshness() {
  if (!state.fetchedAt) return;
  const ago = Math.round((Date.now() - new Date(state.fetchedAt).getTime()) / 60000);
  const txt = ago < 1 ? 'just now' : ago < 60 ? `${ago} min ago` : `${Math.round(ago/60)} h ago`;
  $('#freshness').textContent = state.partial
    ? `⚠ Partial data (fetch interrupted ${txt}) — Refresh to resume`
    : state.staticMode
      ? `Data fetched ${txt} · auto-updates every 3h`
      : `Data fetched ${txt}`;
}

function escapeHtml(s) {
  return String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}

// ---- Tag Explorer -----------------------------------------------------------

// tagId -> { id, name, total, window, popular } across all upcoming games.
function aggregateTags() {
  const { monthStartIso, endIso } = windowBounds(state.tagWindowMonths);
  const stats = new Map();
  for (const g of state.games) {
    if (!g.tags || !g.tags.length) continue;
    const inWin = g.releaseDate && g.releaseDate >= monthStartIso && g.releaseDate < endIso;
    const isPop = g.rank <= state.tagThreshold;
    for (const id of g.tags) {
      let s = stats.get(id);
      if (!s) { s = { id, name: state.tagNames[id] || `#${id}`, total: 0, window: 0, popular: 0 }; stats.set(id, s); }
      s.total += 1;
      if (inWin) {
        s.window += 1;
        if (isPop) s.popular += 1;
      }
    }
  }
  return stats;
}

function renderTagsView() {
  state.tagWindowMonths = +$('#tag-window').value;
  state.tagThreshold = +$('#tag-threshold').value;

  const stats = aggregateTags();
  const sorted = [...stats.values()].sort((a, b) => b.window - a.window || b.total - a.total);

  // searchable datalist of all tag names
  $('#tag-options').innerHTML = sorted
    .map((s) => `<option value="${escapeHtml(s.name)}"></option>`).join('');

  renderTagLeaderboard(sorted);
  renderTagDetail();

  const ago = state.fetchedAt
    ? `Data ${Math.round((Date.now() - new Date(state.fetchedAt).getTime()) / 60000)} min old` : '';
  $('#tag-freshness').textContent = ago + (state.staticMode ? ' · auto-updates every 3h' : '');
  $('#tag-stats').textContent = `${stats.size.toLocaleString()} tags across ${state.games.length.toLocaleString()} upcoming games`;
}

function renderTagLeaderboard(sorted) {
  const board = $('#tag-leaderboard');
  const top = sorted.filter((s) => s.window > 0).slice(0, 40);
  if (top.length === 0) { board.innerHTML = '<p class="legend-note">No tagged games in this window.</p>'; return; }
  const max = top[0].window || 1;
  board.innerHTML = top.map((s) => {
    const w = Math.max(4, Math.round((s.window / max) * 120));
    const hot = s.popular > 0 ? `<span class="tr-hot">🔥 ${s.popular}</span>` : '<span class="tr-hot"></span>';
    return `<div class="tag-row${s.id === state.selectedTag ? ' selected' : ''}" data-tag="${s.id}">
      <span class="tr-name">${escapeHtml(s.name)}</span>
      ${hot}
      <span class="tr-counts"><span class="tr-bar" style="width:${w}px"></span> <b>${s.window}</b> in window</span>
    </div>`;
  }).join('');
  board.querySelectorAll('.tag-row[data-tag]').forEach((row) => {
    row.addEventListener('click', () => selectTag(+row.dataset.tag));
  });
}

function selectTag(id) {
  state.selectedTag = id;
  $('#tag-search').value = state.tagNames[id] || '';
  renderTagsView();
}

function renderTagDetail() {
  const id = state.selectedTag;
  const title = $('#tag-detail-title');
  const summary = $('#tag-detail-summary');
  const hist = $('#tag-histogram');
  const comps = $('#tag-competitors');

  if (id == null) {
    title.textContent = 'Pick a genre';
    summary.textContent = 'Choose a tag above or click a row to see when its releases cluster and who the big competitors are.';
    hist.innerHTML = '';
    comps.innerHTML = '';
    return;
  }

  const name = state.tagNames[id] || `#${id}`;
  const { monthStartIso, endIso } = windowBounds(state.tagWindowMonths);
  const games = state.games.filter((g) => g.tags && g.tags.includes(id));
  const inWin = games.filter((g) => g.releaseDate && g.releaseDate >= monthStartIso && g.releaseDate < endIso);
  const popular = inWin.filter((g) => g.rank <= state.tagThreshold).length;

  title.textContent = `${name}`;
  summary.innerHTML = `<b>${inWin.length}</b> releasing in window · <b>${popular}</b> high-wishlist · ` +
    `${games.length.toLocaleString()} upcoming total in genre.`;

  // Monthly histogram across the window.
  const t = todayParts();
  const months = [];
  for (let o = 0; o < state.tagWindowMonths; o++) {
    const y = t.y + Math.floor((t.m + o) / 12);
    const m = (t.m + o) % 12;
    months.push({ y, m, total: 0, popular: 0 });
  }
  for (const g of inWin) {
    const { y, m } = isoToParts(g.releaseDate);
    const bucket = months.find((b) => b.y === y && b.m === m);
    if (bucket) { bucket.total += 1; if (g.rank <= state.tagThreshold) bucket.popular += 1; }
  }
  const maxM = Math.max(1, ...months.map((b) => b.total));
  hist.innerHTML = months.map((b) => {
    const pct = Math.round((b.total / maxM) * 100);
    const hotPct = b.total ? Math.round((b.popular / b.total) * 100) : 0;
    return `<div class="th-row" title="${b.popular} high-wishlist of ${b.total}">
      <span class="th-label">${MONTH_NAMES[b.m].slice(0, 3)} ${String(b.y).slice(2)}</span>
      <span class="th-track"><span class="th-fill${hotPct >= 50 ? ' hot' : ''}" style="width:${pct}%"></span></span>
      <span class="th-val">${b.total}</span>
    </div>`;
  }).join('');

  // Biggest competitors in this genre & window (followers first, then rank).
  const top = inWin
    .slice()
    .sort((a, b) => (b.followers || 0) - (a.followers || 0) || a.rank - b.rank)
    .slice(0, 10);
  comps.innerHTML = top.map((g) => {
    const foll = g.followers != null
      ? `<span class="co-foll">★ ${fmtCount(g.followers)}</span>`
      : `<span class="co-foll" title="popularity rank">#${g.rank}</span>`;
    return `<li data-appid="${g.appid}">
      <span class="co-name">${escapeHtml(g.name)}</span>
      ${foll}
      <span class="co-date">${fmtReleaseShort(g)}</span>
    </li>`;
  }).join('');
  comps.querySelectorAll('li[data-appid]').forEach((li) => {
    li.addEventListener('click', () =>
      window.open(`https://store.steampowered.com/app/${li.dataset.appid}`, '_blank', 'noopener'));
  });
}

// ---- View switching ---------------------------------------------------------

function renderActiveView() {
  if (state.activeView === 'tags') renderTagsView();
  else render();
}

function switchView(tool) {
  state.activeView = tool;
  document.querySelectorAll('.tab[data-tool]').forEach((b) =>
    b.classList.toggle('active', b.dataset.tool === tool));
  $('#view-calendar').classList.toggle('hidden', tool !== 'calendar');
  $('#view-tags').classList.toggle('hidden', tool !== 'tags');
  renderActiveView();
}

